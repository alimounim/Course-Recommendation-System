def get_allowed_range(level_choice_num):
    """Maps academic level number (1-8) to min/max course number range."""
    ranges = {
        1: (100, 199), 2: (100, 199), 3: (200, 299), 4: (200, 299),
        5: (300, 399), 6: (300, 399), 7: (400, 499), 8: (400, 499)
    }
    return ranges.get(level_choice_num, (100, 499))

def extract_course_number(course_id):
    """Extracts the main number from a course ID string."""
    try:
        match = re.search(r'[a-z]{2,}\s*(\d{1,3})[a-z]?', str(course_id).lower())
        if match: return int(match.group(1))
        num_part = re.search(r'\d+', str(course_id))
        return int(num_part.group()) if num_part else 0
    except: return 0

def filter_courses_by_level(df, min_level, max_level, id_column='course number'):
    """Adds 'course_num_int' column and filters DataFrame by level range."""
    if id_column not in df.columns:
        print(f"Error: ID column '{id_column}' not found for level filtering.")
        return pd.DataFrame()
    df_copy = df.copy()
    # Use .loc to avoid SettingWithCopyWarning when adding column
    df_copy.loc[:, 'course_num_int'] = df_copy[id_column].apply(extract_course_number)
    filtered = df_copy[(df_copy['course_num_int'] >= min_level) & (df_copy['course_num_int'] <= max_level)]
    # Avoid inplace modification or chained indexing; return filtered DF without temp column
    return filtered.drop(columns=['course_num_int'], errors='ignore')


def check_prerequisites_v2(course, taken_courses_list, cs_df, level_choice, selected_courses_list=None, id_column='course number'):
    """ Checks if prerequisites for a course are met, handling 'and'/'or' logic using restricted eval. """
    # --- Full Implementation ---
    if selected_courses_list is None: selected_courses_list = []
    available_courses = set(str(c).strip().lower() for c in taken_courses_list + selected_courses_list if c is not None)
    course_lower = str(course).strip().lower()
    # Ensure cs_df id_column is comparable (string, lower)
    if id_column not in cs_df.columns: return True # Cannot check if column missing
    prereq_row = cs_df[cs_df[id_column].astype(str).str.strip().str.lower() == course_lower]
    if prereq_row.empty: return True # Assume no prereqs if not in CS list

    prereq_data = prereq_row['prerequisite(s)'].iloc[0]
    prereq_str = str(prereq_data) if pd.notna(prereq_data) else ''
    if not prereq_str or prereq_str.strip().lower() == 'none': return True

    original_prereq_str = prereq_str
    expression = original_prereq_str.strip().lower()
    course_codes = set(re.findall(r'([a-z]{2,}\s*\d{1,3}[a-z]?)', expression))

    if not course_codes and expression:
        print(f"Debug: Prereq for '{course}' ('{original_prereq_str}') non-standard text. Assuming unmet.")
        return False

    eval_context = {}
    all_prereqs_mentioned_individually_met = True

    for code in course_codes:
        is_met = False
        if course_lower == 'math 141' and level_choice == 2 and code == 'math 110': is_met = True
        elif code in available_courses: is_met = True
        else: all_prereqs_mentioned_individually_met = False
        safe_key = re.sub(r'[^a-zA-Z0-9_]', '_', code)
        if safe_key.isidentifier(): # Check if it's a valid Python identifier
             eval_context[safe_key] = is_met
        else:
             print(f"Warning: Generated invalid identifier '{safe_key}' from '{code}' for prereq eval.")
             # Cannot include this in eval context safely, may cause evaluation failure
             # Depending on logic (AND/OR), this might mean the requirement cannot be met
             pass # Or decide to return False immediately if any part is invalid

    eval_expression = expression
    eval_expression = re.sub(r'\band\b', ' and ', eval_expression)
    eval_expression = re.sub(r'\bor\b', ' or ', eval_expression)
    eval_expression = re.sub(r'\bnot\b', ' not ', eval_expression)
    eval_expression = eval_expression.replace(',', ' and ')
    eval_expression = eval_expression.replace('&', ' and ')
    eval_expression = eval_expression.replace('/', ' or ')

    sorted_course_codes = sorted(list(course_codes), key=len, reverse=True)
    for code in sorted_course_codes:
        safe_key = re.sub(r'[^a-zA-Z0-9_]', '_', code)
        if safe_key.isidentifier(): # Only substitute valid identifiers
            escaped_code = re.escape(code)
            eval_expression = re.sub(r'\b' + escaped_code + r'\b', safe_key, eval_expression)

    if eval_expression.count('(') != eval_expression.count(')'):
        print(f"Warning: Unbalanced parentheses in prereq for '{course}'. Assuming unmet.")
        return False
    eval_expression = ' '.join(eval_expression.split())

    try:
        eval_context['True'] = True; eval_context['False'] = False
        potential_leftovers = re.findall(r'[a-zA-Z_][a-zA-Z0-9_]+', eval_expression)
        valid_tokens = set(eval_context.keys()) | {'and', 'or', 'not', 'True', 'False'}
        unknown_tokens = [token for token in potential_leftovers if token not in valid_tokens]
        if unknown_tokens:
             print(f"Warning: Unknown tokens {unknown_tokens} in prereq expr for '{course}'. Assuming unmet.")
             return False

        result = eval(eval_expression, {"__builtins__": {}}, eval_context)
        # print(f"Debug: Evaluated prereq for '{course}': '{eval_expression}' -> {result}")
        return bool(result)
    except Exception as e:
        print(f"Error evaluating prereq '{eval_expression}' for {course}: {e}")
        has_logic_keywords = any(kw in expression for kw in [' and ', ' or ', '(', ')', ','])
        if not has_logic_keywords and len(course_codes) > 0:
            return all_prereqs_mentioned_individually_met
        else: return False
    # --- End Full Implementation ---

