def get_choice_from_list(options_list, prompt_message):
    """Displays options, gets numbered choice, returns (choice_str, choice_num)."""
    print(f"\n{prompt_message}")
    if not options_list: print("No options available."); return None, None
    for i, option in enumerate(options_list, 1): print(f"{i}. {option}")
    while True:
        try:
            choice_num = int(input("Enter the number of your choice: "))
            if 1 <= choice_num <= len(options_list): return options_list[choice_num - 1], choice_num
            else: print(f"Invalid number. Please enter 1-{len(options_list)}.")
        except ValueError: print("Invalid input. Please enter a number.")

def get_allowed_range(level_choice_num):
    """Maps academic level number (1-8) to min/max course number range."""
    ranges = {
        1: (100, 199), 2: (100, 199), 3: (200, 299), 4: (200, 299),
        5: (300, 399), 6: (300, 399), 7: (400, 499), 8: (400, 499)
    }
    return ranges.get(level_choice_num, (100, 499))

def extract_course_number(course_id):
    """Extracts the main number from a course ID string."""
    try:
        num_part = re.search(r'\d+', str(course_id))
        return int(num_part.group()) if num_part else 0
    except: return 0

def parse_distribution_str(distribution_str):
    """Parses comma/space/plus separated distribution codes."""
    if pd.isna(distribution_str) or not distribution_str: return []
    codes = re.split(r'[,\s\+]+', str(distribution_str))
    return [code.strip().upper() for code in codes if code.strip()]

def preprocess_text(text):
    """Cleans text for TF-IDF."""
    if pd.isna(text): return ""
    text = str(text).lower()
    text = text.translate(str.maketrans('', '', string.punctuation))
    words = text.split()
    words = [word for word in words if word not in stop_words]
    return " ".join(words)

def perform_topic_search_tfidf(filtered_df_input):
    """ Performs TF-IDF search *on the provided pre-filtered DataFrame*. """
    print("\n--- Searching by Topic within filtered results ---")
    if filtered_df_input.empty:
        print("Cannot perform topic search as no courses match the initial Level/Semester criteria.")
        return

    # Work on a copy
    courses_df = filtered_df_input.copy()

    text_columns = ['course title', 'course description', 'course description.1']
    valid_text_columns = [col for col in text_columns if col in courses_df.columns]
    if not valid_text_columns:
        print(f"Error: Could not find required text columns {text_columns} for topic search.")
        return
    print(f"Searching within columns: {valid_text_columns}")

    # Combine text, handle NaNs (might already be done, but safe to repeat)
    courses_df['text_for_search'] = courses_df[valid_text_columns].fillna('').astype(str).agg(' '.join, axis=1)
    print("Preprocessing course text...")
    courses_df['preprocessed_text'] = courses_df['text_for_search'].apply(preprocess_text)

    print("Building TF-IDF model (on filtered data)...")
    vectorizer = TfidfVectorizer()
    tfidf_matrix = vectorizer.fit_transform(courses_df['preprocessed_text']) # Fit only on filtered data

    query = input("Enter your topic query (e.g., 'introduction to machine learning'): ").strip()
    if not query: print("No query entered."); return
    preprocessed_query = preprocess_text(query)
    if not preprocessed_query: print("Query invalid after preprocessing."); return

    query_vector = vectorizer.transform([preprocessed_query]) # Transform using the fitted vectorizer
    print("Calculating similarity...")
    cosine_similarities = cosine_similarity(query_vector, tfidf_matrix).flatten()

    N = 10
    similarity_threshold = 0.05 # Adjust as needed
    top_n_indices_local = np.argsort(cosine_similarities)[-N:][::-1] # Indices relative to the filtered_df

    # Filter local indices by threshold
    relevant_indices_local = [i for i in top_n_indices_local if cosine_similarities[i] > similarity_threshold]

    if not relevant_indices_local:
        print(f"\nNo relevant courses found within the filtered set for query: '{query}'")
        return

    print(f"\nTop {len(relevant_indices_local)} relevant courses found for query: '{query}'")

    # Retrieve results using the local indices on the input DataFrame
    results_df = courses_df.iloc[relevant_indices_local].copy()
    results_df['similarity_score'] = cosine_similarities[relevant_indices_local]

    display_cols = ['course number', 'course title', 'semester', 'program', 'similarity_score', 'course description']
    display_cols = [col for col in display_cols if col in results_df.columns]
    results_df = results_df.sort_values(by='similarity_score', ascending=False)
    display(results_df[display_cols])

