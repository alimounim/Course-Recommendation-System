def load_course_data(file_path, sheet_name):
    """Loads and normalizes string columns."""
    try:
        df = pd.read_excel(file_path, engine='openpyxl', sheet_name=sheet_name)
        print(f"Loaded sheet '{sheet_name}' from {file_path}")
         # Apply basic normalization (lowercase strings)
        string_cols = df.select_dtypes(include=['object']).columns
        for col in string_cols:
             # Use .loc to potentially avoid SettingWithCopyWarning
             # Ensure conversion to string first for robustness
             df.loc[:, col] = df[col].apply(lambda x: str(x).strip().lower() if pd.notna(x) else x)
        # Ensure 'prerequisite(s)' column exists, fillna for safety
        if 'prerequisite(s)' not in df.columns:
             df['prerequisite(s)'] = '' # Add if missing, initialize with empty string
        df['prerequisite(s)'] = df['prerequisite(s)'].fillna('') # Fill NaN with empty string
        return df
    except FileNotFoundError:
        print(f"Error: The file {file_path} was not found.")
        return None
    except Exception as e:
        print(f"Error loading data from {file_path}, sheet {sheet_name}: {e}")
        return None

